CREATE VIEW public.v_contest_standings AS
 WITH totals AS (
         SELECT p.contest_id,
            p.user_id,
            count(*) FILTER (WHERE cc.solved) AS solved,
            COALESCE(sum((cc.solve_minute + (cc.wrong * c.penalty_minutes))) FILTER (WHERE cc.solved), (0)::numeric) AS penalty
           FROM ((public.contest_participants p
             JOIN public.contests c ON ((c.id = p.contest_id)))
             LEFT JOIN public.v_contest_cells cc ON (((cc.contest_id = p.contest_id) AND (cc.user_id = p.user_id))))
          GROUP BY p.contest_id, p.user_id
        )
 SELECT t.contest_id,
    rank() OVER (PARTITION BY t.contest_id ORDER BY t.solved DESC, t.penalty) AS rank,
    t.user_id,
    u.username,
    u.full_name,
    t.solved,
    t.penalty
   FROM (totals t
     JOIN public.users u ON ((u.id = t.user_id)));


