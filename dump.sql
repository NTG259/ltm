CREATE VIEW public.v_contest_cells AS
 WITH subs AS (
         SELECT s.contest_id,
            s.user_id,
            s.problem_id,
            s.status,
            s.verdict,
            s.created_at,
            min(s.created_at) FILTER (WHERE ((s.verdict)::text = 'AC'::text)) OVER (PARTITION BY s.contest_id, s.user_id, s.problem_id) AS first_ac_at
           FROM (public.submissions s
             JOIN public.contests c_1 ON ((c_1.id = s.contest_id)))
          WHERE (s.created_at < c_1.end_at)
        )
 SELECT sb.contest_id,
    sb.user_id,
    sb.problem_id,
    cp.label,
    COALESCE(bool_or(((sb.verdict)::text = 'AC'::text)), false) AS solved,
    count(*) FILTER (WHERE (((sb.status)::text = 'FINISHED'::text) AND ((sb.verdict)::text <> ALL ((ARRAY['AC'::character varying, 'CE'::character varying, 'SEC'::character varying])::text[])) AND ((sb.first_ac_at IS NULL) OR (sb.created_at < sb.first_ac_at)))) AS wrong,
    count(*) FILTER (WHERE (((sb.status)::text <> ALL ((ARRAY['FINISHED'::character varying, 'FAILED'::character varying])::text[])) AND ((sb.first_ac_at IS NULL) OR (sb.created_at < sb.first_ac_at)))) AS pending,
    (floor((EXTRACT(epoch FROM (min(sb.first_ac_at) - c.start_at)) / (60)::numeric)))::integer AS solve_minute,
    min(sb.first_ac_at) AS first_ac_at,
    COALESCE((min(sb.first_ac_at) = min(min(sb.first_ac_at)) OVER (PARTITION BY sb.contest_id, sb.problem_id)), false) AS first_solve
   FROM ((subs sb
     JOIN public.contests c ON ((c.id = sb.contest_id)))
     JOIN public.contest_problems cp ON (((cp.contest_id = sb.contest_id) AND (cp.problem_id = sb.problem_id))))
  GROUP BY sb.contest_id, sb.user_id, sb.problem_id, cp.label, c.start_at;


ALTER VIEW public.v_contest_cells OWNER TO neondb_owner;

