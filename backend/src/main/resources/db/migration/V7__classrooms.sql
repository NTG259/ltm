-- =============================================================================
-- Lớp học: classrooms, classroom_students, classroom_contests
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Lớp học
-- -----------------------------------------------------------------------------
CREATE TABLE classrooms (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    semester    VARCHAR(50),                        -- ví dụ: "HK1/2025"
    created_by  BIGINT       REFERENCES users(id) ON DELETE SET NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE  classrooms IS 'Lớp học theo kỳ học thực tế, do admin tạo và quản lý.';
COMMENT ON COLUMN classrooms.semester IS 'Kỳ học tự do, ví dụ HK1/2025 hoặc K65-HK2.';

-- -----------------------------------------------------------------------------
-- Sinh viên trong lớp  (mỗi sinh viên chỉ ở 1 lớp)
-- -----------------------------------------------------------------------------
CREATE TABLE classroom_students (
    classroom_id BIGINT      NOT NULL REFERENCES classrooms(id) ON DELETE CASCADE,
    user_id      BIGINT      NOT NULL REFERENCES users(id)      ON DELETE CASCADE,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (classroom_id, user_id),
    CONSTRAINT uq_classroom_students_user UNIQUE (user_id)   -- 1 sinh viên chỉ thuộc 1 lớp
);

CREATE INDEX ix_classroom_students_classroom ON classroom_students (classroom_id);

COMMENT ON CONSTRAINT uq_classroom_students_user ON classroom_students IS
    'Mỗi sinh viên chỉ được xếp vào 1 lớp tại một thời điểm.';

-- -----------------------------------------------------------------------------
-- Kỳ thi được gán cho lớp
-- -----------------------------------------------------------------------------
CREATE TABLE classroom_contests (
    classroom_id BIGINT      NOT NULL REFERENCES classrooms(id) ON DELETE CASCADE,
    contest_id   BIGINT      NOT NULL REFERENCES contests(id)   ON DELETE CASCADE,
    assigned_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (classroom_id, contest_id)
);

CREATE INDEX ix_classroom_contests_contest ON classroom_contests (contest_id);
