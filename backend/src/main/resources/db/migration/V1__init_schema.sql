-- GET /api/problems: totalSubmissions, acceptedSubmissions, testCount.
CREATE VIEW v_problem_stats AS
SELECT p.id                                                    AS problem_id,
       (SELECT count(*) FROM test_cases t WHERE t.problem_id = p.id) AS test_count,
       count(s.id)                                             AS total_submissions,
       count(s.id) FILTER (WHERE s.verdict = 'AC')             AS accepted_submissions,
       count(DISTINCT s.user_id) FILTER (WHERE s.verdict = 'AC') AS solved_users
FROM problems p
LEFT JOIN submissions s ON s.problem_id = p.id AND s.status = 'FINISHED'
GROUP BY p.id;

-- Ô (thí sinh, bài) của bảng xếp hạng chung: điểm cao nhất, số lần nộp tới khi AC.
CREATE VIEW v_user_problem_best AS
WITH finished AS (
    SELECT s.user_id, s.problem_id, s.score, s.verdict, s.created_at,
           min(s.created_at) FILTER (WHERE s.verdict = 'AC')
               OVER (PARTITION BY s.user_id, s.problem_id) AS first_ac_at
    FROM submissions s
    JOIN users u ON u.id = s.user_id AND u.role = 'STUDENT'
    WHERE s.status = 'FINISHED'
)
SELECT user_id,
       problem_id,
       max(score)                                                    AS best_score,
       count(*) FILTER (WHERE first_ac_at IS NULL OR created_at <= first_ac_at) AS tries,
       count(*)                                                      AS attempts,
       coalesce(bool_or(verdict = 'AC'), FALSE)                      AS solved,
       min(first_ac_at)                                              AS first_ac_at
FROM finished
GROUP BY user_id, problem_id;

-- GET /api/leaderboard: tổng điểm = tổng điểm cao nhất mỗi bài.
CREATE VIEW v_leaderboard AS
SELECT rank() OVER (ORDER BY sum(b.best_score) DESC, count(*) FILTER (WHERE b.solved) DESC,
                             max(b.first_ac_at) ASC NULLS LAST) AS rank,
       u.id                                  AS user_id,
       u.username,
       u.full_name,
       count(*) FILTER (WHERE b.solved)      AS solved,
       sum(b.best_score)                     AS score,
       sum(b.attempts)                       AS attempts,
       max(b.first_ac_at)                    AS last_ac_at
FROM v_user_problem_best b
JOIN users u ON u.id = b.user_id
GROUP BY u.id;

-- GET /api/contests/:id/standings – ô ICPC (thí sinh, bài) trong một kỳ thi.
CREATE VIEW v_contest_cells AS
WITH subs AS (
    SELECT s.contest_id, s.user_id, s.problem_id, s.status, s.verdict, s.created_at,
           min(s.created_at) FILTER (WHERE s.verdict = 'AC')
               OVER (PARTITION BY s.contest_id, s.user_id, s.problem_id) AS first_ac_at
    FROM submissions s
    JOIN contests c ON c.id = s.contest_id
    WHERE s.created_at < c.end_at
)
SELECT sb.contest_id,
       sb.user_id,
       sb.problem_id,
       cp.label,
       coalesce(bool_or(sb.verdict = 'AC'), FALSE)                           AS solved,
       count(*) FILTER (WHERE sb.status = 'FINISHED' AND sb.verdict NOT IN ('AC', 'CE', 'SEC')
                          AND (sb.first_ac_at IS NULL OR sb.created_at < sb.first_ac_at)) AS wrong,
       count(*) FILTER (WHERE sb.status NOT IN ('FINISHED', 'FAILED')
                          AND (sb.first_ac_at IS NULL OR sb.created_at < sb.first_ac_at)) AS pending,
       floor(extract(epoch FROM min(sb.first_ac_at) - c.start_at) / 60)::int AS solve_minute,
       min(sb.first_ac_at)                                                   AS first_ac_at,
       -- Người giải bài này sớm nhất trong kỳ thi (ô "first blood" trên bảng xếp hạng).
       coalesce(min(sb.first_ac_at) = min(min(sb.first_ac_at))
                    OVER (PARTITION BY sb.contest_id, sb.problem_id), FALSE) AS first_solve
FROM subs sb
JOIN contests c          ON c.id = sb.contest_id
JOIN contest_problems cp ON cp.contest_id = sb.contest_id AND cp.problem_id = sb.problem_id
GROUP BY sb.contest_id, sb.user_id, sb.problem_id, cp.label, c.start_at;

-- Bảng xếp hạng ICPC: số bài AC giảm dần, rồi tổng phút phạt tăng dần.
-- Thí sinh đã đăng ký nhưng chưa nộp vẫn có một dòng (0 bài, 0 phút).
CREATE VIEW v_contest_standings AS
WITH totals AS (
    SELECT p.contest_id,
           p.user_id,
           count(*) FILTER (WHERE cc.solved)                                       AS solved,
           coalesce(sum(cc.solve_minute + cc.wrong * c.penalty_minutes)
                    FILTER (WHERE cc.solved), 0)                                    AS penalty
    FROM contest_participants p
    JOIN contests c ON c.id = p.contest_id
    LEFT JOIN v_contest_cells cc ON cc.contest_id = p.contest_id AND cc.user_id = p.user_id
    GROUP BY p.contest_id, p.user_id
)
SELECT t.contest_id,
       rank() OVER (PARTITION BY t.contest_id ORDER BY t.solved DESC, t.penalty ASC) AS rank,
       t.user_id,
       u.username,
       u.full_name,
       t.solved,
       t.penalty
FROM totals t
JOIN users u ON u.id = t.user_id;
